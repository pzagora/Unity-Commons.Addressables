using System;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.AddressableAssets;
using UnityEditor.AddressableAssets.Settings;
using UnityEditor.AddressableAssets.Settings.GroupSchemas;

namespace Commons.Addressables.Editor
{
    /// <summary>
    /// Generates <c>const string</c> keys for every address and label: one nested class per group (and per address
    /// path segment), plus a <c>Labels</c> class. Regenerates whenever the Addressables settings change, writing the file
    /// only when its contents differ. Disabled until a keys path is set in Project Settings ▸ zagora.dev ▸ Commons Addressables.
    /// </summary>
    [InitializeOnLoad]
    internal static class AddressableKeysGenerator
    {
        private const string HEADER =
            "// <auto-generated>\n" +
            "// Generated by Commons.Addressables from the project's Addressables groups and labels. Do not edit:\n" +
            "// changes are overwritten whenever Addressables settings change.\n" +
            "// </auto-generated>\n";

        private const string LABELS_CLASS = "Labels";
        private const char SEPARATOR = '/';

        private static bool _scheduled;

        static AddressableKeysGenerator()
        {
            AddressableAssetSettings.OnModificationGlobal -= OnModification;
            AddressableAssetSettings.OnModificationGlobal += OnModification;
        }

        public static void Schedule()
        {
            if (_scheduled)
                return;

            _scheduled = true;
            EditorApplication.delayCall += Run;
        }

        /// <summary>Generates the keys file now. Returns <c>true</c> when the file was written.</summary>
        public static bool Generate()
        {
            var config = AddressablesConventionSettings.instance;
            var settings = AddressableAssetSettingsDefaultObject.Settings;
            if (!config.CanGenerateKeys || settings == null)
                return false;

            var code = BuildCode(settings, config);
            var path = config.KeysPath;

            if (File.Exists(path) && File.ReadAllText(path) == code)
                return false;

            var directory = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(directory))
                Directory.CreateDirectory(directory);

            File.WriteAllText(path, code);
            AssetDatabase.ImportAsset(path);
            return true;
        }

        private static void Run()
        {
            _scheduled = false;
            Generate();
        }

        private static void OnModification(AddressableAssetSettings settings, AddressableAssetSettings.ModificationEvent modification, object data)
            => Schedule();

        private static string BuildCode(AddressableAssetSettings settings, AddressablesConventionSettings config)
        {
            var root = new KeyNode(config.KeysClass);

            var labels = root.Child(LABELS_CLASS);
            foreach (var label in settings.GetLabels())
                labels.AddConstant(label, label);

            foreach (var group in settings.groups)
            {
                if (group == null || group.entries.Count == 0 || group.HasSchema<PlayerDataGroupSchema>())
                    continue;

                var groupNode = root.Child(group.Name);
                foreach (var entry in group.entries)
                    AddEntry(groupNode, group.Name, entry.address);
            }

            var builder = new StringBuilder(HEADER).AppendLine();
            var hasNamespace = !string.IsNullOrEmpty(config.KeysNamespace);

            if (hasNamespace)
                builder.Append("namespace ").AppendLine(config.KeysNamespace).AppendLine("{");

            root.Write(builder, hasNamespace ? 1 : 0);

            if (hasNamespace)
                builder.AppendLine("}");

            return builder.ToString();
        }

        private static void AddEntry(KeyNode groupNode, string groupName, string address)
        {
            if (string.IsNullOrEmpty(address))
                return;

            var segments = address.Split(new[] { SEPARATOR }, StringSplitOptions.RemoveEmptyEntries);
            if (segments.Length == 0)
                return;

            var first = segments.Length > 1 && segments[0] == groupName ? 1 : 0;

            var node = groupNode;
            for (var i = first; i < segments.Length - 1; i++)
                node = node.Child(segments[i]);

            node.AddConstant(Path.GetFileNameWithoutExtension(segments[segments.Length - 1]), address);
        }
    }
}
